"""Coverage table: can skin.py target every Melee fighter's costume? Reads structure only (joint counts and names,
DObj counts, matanim presence) from SKIN_MELEE_IMAGE's Pl<code>Nr.dat + PlCo.dat; writes names and counts only.

    coverage.py [--out coverage.md] [--json coverage.json]
"""
import argparse, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import skin, paths
import melee_fighters as B, mex_hsd

SPECIAL = {"gameandwatch": "flat model: thin DObjs per pose; a 3D source skins but reads as a 3D body - noted, not blocked",
           "popo": "Ice Climbers: Popo and Nana are separate costume files (target each)",
           "nana": "Ice Climbers: Nana's own costume file", "sheik": "Zelda/Sheik: separate files, transform swaps them",
           "zelda": "Zelda/Sheik: separate files"}
TEMPLATES = paths.MAPS


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default=os.path.join(paths.DATA, "coverage.md")); ap.add_argument("--json")
    a = ap.parse_args()
    iso = paths.melee_image()
    g = mex_hsd.Gcm(iso); tmp = paths.work("skin-coverage")
    plco = os.path.join(tmp, "PlCo.dat"); open(plco, "wb").write(g.read("PlCo.dat"))
    rows = []
    for name, (kind, code, _, _) in B.FIGHTERS.items():
        if name == "captain": continue
        r = {"fighter": name, "kind": kind, "file": "Pl%sNr.dat" % code}
        try:
            p = os.path.join(tmp, r["file"]); open(p, "wb").write(g.read(r["file"]))
            t = skin.read_target(p, name, plco)
            names = [j["name"] for j in t["joints"]]
            r.update(joints=len(names), dobjs=len(t["dobjs"]), matanim=any(s.endswith("matanim_joint") for s in t["publics"]),
                     common=sum(1 for n in names if not n.startswith("ExtraN")),
                     extra=[i for i, n in enumerate(names) if n.startswith("ExtraN")], ok=True)
            os.remove(p)
        except Exception as e:
            r.update(ok=False, error=str(e)[:120])
        r["template"] = os.path.exists(os.path.join(TEMPLATES, name + ".bones.json"))
        r["note"] = SPECIAL.get(name, "")
        rows.append(r)
    with open(a.out, "w") as f:
        f.write("# skin.py target coverage (generated by coverage.py; names and counts only)\n\n")
        f.write("| fighter | kind | file | joints | named common | extra joints (index) | DObjs | eye matanim | groups read | Brawl template | note |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
        for r in rows:
            if r["ok"]:
                f.write("| %s | %d | %s | %d | %d | %s | %d | %s | yes | %s | %s |\n" % (r["fighter"], r["kind"], r["file"], r["joints"], r["common"],
                        ",".join(map(str, r["extra"])) or "-", r["dobjs"], "yes" if r["matanim"] else "no", "yes" if r["template"] else "auto-map", r["note"]))
            else:
                f.write("| %s | %d | %s | - | - | - | - | - | **no**: %s | - | %s |\n" % (r["fighter"], r["kind"], r["file"], r["error"], r["note"]))
    if a.json: json.dump(rows, open(a.json, "w"), indent=1)
    print(open(a.out).read())


if __name__ == "__main__":
    main()
