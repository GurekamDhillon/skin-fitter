"""Generate starter bone-map templates (bone NAMES only) for every Melee target that has a Brawl counterpart.
Reads the Brawl skeleton names from your extracted Brawl files (model_export) and the Melee joint names from
SKIN_MELEE_IMAGE (PlCo + Pl<code>Nr), runs the auto-mapper and writes maps/<melee>.bones.json. Hand-checked templates
(those with "checked": true) are not overwritten.

    make_templates.py --brawl <your unpacked Brawl>/files/fighter
"""
import argparse, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import skin, paths
import mex_hsd, melee_fighters as B

# Melee target -> Brawl/Project M source folder; Melee-only fighters use the nearest skeleton
PAIRS = {"mario": "mario", "drmario": "mario", "luigi": "luigi", "fox": "fox", "falco": "falco", "falcon": "captain",
         "dk": "donkey", "kirby": "kirby", "bowser": "koopa", "link": "link", "younglink": "toonlink", "ness": "ness",
         "peach": "peach", "popo": "popo", "nana": "popo", "pikachu": "pikachu", "pichu": "pikachu", "samus": "samus",
         "yoshi": "yoshi", "jigglypuff": "purin", "marth": "marth", "roy": "marth", "zelda": "zelda", "sheik": "sheik",
         "gameandwatch": "gamewatch", "ganondorf": "ganon", "mewtwo": "lucario"}
NOTES = {"drmario": "Brawl has no Dr. Mario: Mario's skeleton (same rig family); expect a close fit",
         "pichu": "Brawl has no Pichu: Pikachu's skeleton; proportions differ (bigger head, ears), check the ears",
         "younglink": "Brawl has no Young Link: Toon Link's skeleton; similar bone set, child proportions",
         "roy": "Project M Roy is a separate fighter; without its files, Marth's skeleton (same family) seeds the map",
         "mewtwo": "Project M Mewtwo is not on the retail disc; Lucario's skeleton (tail, digitigrade legs) seeds it; low confidence expected",
         "nana": "Ice Climbers: Popo's skeleton for Nana's file"}


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--brawl", required=True, help="your unpacked Brawl fighter/ folder")
    a = ap.parse_args()
    g = mex_hsd.Gcm(paths.melee_image())
    tmp = paths.work("skin-templates"); os.makedirs(paths.MAPS, exist_ok=True)
    plco = os.path.join(tmp, "PlCo.dat"); open(plco, "wb").write(g.read("PlCo.dat"))
    for melee, brawl in PAIRS.items():
        out = os.path.join(paths.MAPS, melee + ".bones.json")
        if os.path.exists(out) and json.load(open(out)).get("checked"): print("keep (checked):", melee); continue
        d = os.path.join(a.brawl, brawl)
        pac = next((os.path.join(d, f) for f in sorted(os.listdir(d)) if f.lower().endswith("00.pac")), None) if os.path.isdir(d) else None
        if not pac: print("no source for", melee, "(", brawl, ")"); continue
        try:
            src = skin.export_source(pac, os.path.join(tmp, brawl))
        except skin.SourceError as e:
            print("skip", melee, e); continue
        code = B.FIGHTERS[melee][1]; nr = os.path.join(tmp, "Pl%sNr.dat" % code); open(nr, "wb").write(g.read("Pl%sNr.dat" % code))
        tgt = skin.read_target(nr, melee, plco); os.remove(nr)
        mp = skin.automap(src, tgt)
        conf = sum(v["confidence"] for v in mp["source_to_target"].values()) / len(mp["source_to_target"])
        json.dump({"_about": "Generated by make_templates.py: names only. Source rig %s -> Melee %s. %s" % (brawl, melee, NOTES.get(melee, "")),
                   "source_character": brawl, "checked": False, "mean_confidence": round(conf, 2),
                   "source_bones": [b["name"] for b in src["bones"]],
                   "source_to_target": {k: v["target"] for k, v in mp["source_to_target"].items()}}, open(out, "w"), indent=1)
        print("%-12s <- %-10s %3d bones, mean confidence %.2f" % (melee, brawl, len(src["bones"]), conf))


if __name__ == "__main__":
    main()
